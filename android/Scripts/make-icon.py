#!/usr/bin/env python3
"""The launcher icon: the iOS icon's PixelSparkline on the dark panel
(ios/Scripts/make-icon.py), as an adaptive icon's vector layers.

A 9 x 9 grid of unlit cells, a rising trace lit in ink with dimmer cells
beneath it, the newest cell in the accent. The grid takes 62% of the visible
72 dp, as the iOS grid takes 62% of its icon, which keeps it inside the 66 dp
circle every launcher mask leaves whole. The iOS registration marks sit in
the corners a round mask cuts off, so they are left out here. Also writes the
monochrome layer Android 13+ tints for themed icons. Run from android/.
"""
from pathlib import Path

RES = Path(__file__).resolve().parents[1] / "app/src/main/res/drawable"
PANEL = (22, 23, 25)       # --mu-panel (dark); the background layer, @color/jf_icon_background
OFF = (37, 39, 43)         # --mu-pixel-off
INK = (247, 247, 243)      # --mu-ink
ACCENT = (255, 106, 52)    # --mu-accent

COLS = ROWS = 9
TRACE = [1, 2, 2, 4, 3, 5, 6, 6, 8]   # the lit row per column (0 = bottom), as iOS
CANVAS, VISIBLE = 108.0, 72.0


def mix(c, bg, a):
    return tuple(round(x * a + y * (1 - a)) for x, y in zip(c, bg))


def cells():
    """(x, y, size, kind) for every cell; kind is off, ink, near, deep or accent."""
    grid = VISIBLE * 0.62
    pitch = grid / COLS
    cell = pitch * 0.82
    x0 = (CANVAS - grid + (pitch - cell)) / 2
    y0 = x0
    for c in range(COLS):
        lit = TRACE[c]
        for r in range(ROWS):
            if r == lit:
                kind = "accent" if c == COLS - 1 else "ink"
            elif r < lit:
                kind = "near" if lit - r <= 2 else "deep"
            else:
                kind = "off"
            yield x0 + c * pitch, y0 + (ROWS - 1 - r) * pitch, cell, kind


def path(rects):
    return "".join(f"M{x:.2f},{y:.2f}h{s:.2f}v{s:.2f}h{-s:.2f}z" for x, y, s in rects)


def vector(groups):
    body = "\n".join(
        f'    <path android:fillColor="{color}" android:fillAlpha="{alpha}" android:pathData="{path(rects)}" />'
        for color, alpha, rects in groups if rects)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by Scripts/make-icon.py; edit that, not this. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f"{body}\n</vector>\n")


def hexc(rgb):
    return "#%02X%02X%02X" % rgb


def main():
    by = {}
    for x, y, s, kind in cells():
        by.setdefault(kind, []).append((x, y, s))
    colors = {"off": OFF, "deep": mix(INK, PANEL, 0.16), "near": mix(INK, PANEL, 0.38), "ink": INK, "accent": ACCENT}
    full = [(hexc(colors[k]), "1", by.get(k, [])) for k in ("off", "deep", "near", "ink", "accent")]
    (RES / "ic_launcher_foreground.xml").write_text(vector(full))
    # Themed icons: one colour the system picks; brightness by alpha.
    mono = [("#FFFFFFFF", a, by.get(k, [])) for k, a in (("off", "0.18"), ("deep", "0.32"), ("near", "0.55"), ("ink", "1"), ("accent", "1"))]
    (RES / "ic_launcher_monochrome.xml").write_text(vector(mono))
    print(RES / "ic_launcher_foreground.xml")


if __name__ == "__main__":
    main()
